class FeatureBuilder:
    def __init__(self):
        self.raw=pd.read_csv(SNAPSHOT)
        self.wide,_=previous.legacy.load_history()
        self.panels={};self.forecasts={};self.bankframes={}
        self.inputs={str(x.relative_to(ROOT)):sha(x) for x in [SNAPSHOT,ROOT/'research_v3/models/panel_extended.pkl',ROOT/'research_v3/models/data/cbr_extended.csv',ROOT/'research_v4/liquidity/halyk_sell_daily.csv',Path(oxr.__file__),Path(banks.__file__),Path(previous.__file__),ROOT/'final_solution/training/core_experiment.py']}
        save(OUT/'input_receipt.json',{'snapshot_min_date':self.raw.date.min(),'snapshot_max_date':self.raw.date.max(),'snapshot_rows':len(self.raw),'input_sha256':self.inputs,'code_sha256':sha(__file__)})

    def build(self,spec,year):
        key=(spec['since'],spec['delay_hours_after_completed_day'])
        if key not in self.panels:
            self.panels[key]=oxr.build_panel(delay=key[1],since=key[0],raw=self.raw,extended=True)
        p=self.panels[key].copy()
        extras={'none':[],'basis':oxr.BASIS+oxr.COVER,'full':oxr.RET+oxr.BASIS+oxr.COVER,'coverage':oxr.COVER}[spec['family']]
        bank_lag=spec['bank_lag_calendar_days']
        if bank_lag:
            if bank_lag not in self.bankframes:
                bp,groups,receipt=banks.build_panel(extended=True,lag=bank_lag)
                bankcols=groups['halyk']
                provenance=[c for c in bp if c.startswith('halyk_') and (c.endswith('_available_date') or c.endswith('_observation_date'))]
                self.bankframes[bank_lag]=(bp[['date','corridor',*bankcols,*provenance]],bankcols)
                save(OUT/f'halyk_feature_receipt_D{bank_lag}.json',receipt)
            bp,bankcols=self.bankframes[bank_lag]
            p=p.merge(bp,on=['date','corridor'],how='left',validate='one_to_one')
            extras=extras+bankcols
        fmkey=(spec['model'],0 if spec['model']=='synth_zs' else year)
        if fmkey not in self.forecasts:
            filename='chronos2_synth_zs.npz' if fmkey[0]=='synth_zs' else f'chronos2_small_ft_{year}.npz'
            cache=PREVIOUS/'forecasts'/filename;item=np.load(cache)
            base=pd.read_pickle(ROOT/'research_v3/models/panel_extended.pkl')[['date','corridor']]
            fm,cols=previous.legacy.forecast_features(base,self.wide,pd.DatetimeIndex(item['dates']),item['quantiles'],item['grid'])
            self.forecasts[fmkey]=(fm[['date','corridor',*cols]],cols,cache)
        fm,cols,cache=self.forecasts[fmkey]
        p=p.merge(fm,on=['date','corridor'],validate='one_to_one').sort_values(['date','corridor']).reset_index(drop=True)
        return core.add_target(p,5),BASE+cols+extras,cache


def evaluate(p,features,cache,spec,cutoff):
    cutoff=pd.Timestamp(cutoff);val_start=cutoff-pd.DateOffset(years=1)
    tr,va,te=classic.temporal_split(p,5,cutoff,pd.Timestamp(cutoff.year+1,1,1),classic.Spec(spec['name'],months=120,extended=True))
    if spec['local_kzt_calibration']:
        va=va[va.corridor.eq('KZT')];te=te[te.corridor.eq('KZT')]
    history=p[p.date.ge(val_start)&p.date.lt(cutoff)].copy()
    if spec['local_kzt_calibration']:history=history[history.corridor.eq('KZT')]
    future=p.groupby('corridor').date.shift(-5)
    assert (future.loc[tr.index]<val_start).all() and (future.loc[va.index]<cutoff).all()
    fm=[c for c in features if c.startswith('fm_')]
    assert tr[fm].notna().all().all() and va[fm].notna().all().all() and te[fm].notna().all().all()
    model=core.make_model('hist_gradient_boosting',features);model.named_steps['classifier'].set_params(early_stopping=False)
    x=features+['corridor'];t=time.perf_counter()
    model.fit(tr[x],tr.target.astype(int))
    raw_val=model.predict_proba(va[x])[:,1];cal=core.fit_platt_calibrator(raw_val,va.target)
    threshold,_,_=core.choose_frequency_threshold(va,core.apply_platt(cal,raw_val))
    hp=core.apply_platt(cal,model.predict_proba(history[x])[:,1]);hi=core.select_per_corridor_with_cooldown(history,hp,threshold)
    state=core.corridor_selection_state(history,hi)
    portfolio_state=core.selection_state(history,core.select_portfolio_from_candidates(history,hp,hi))
    raw=model.predict_proba(te[x])[:,1];prob=core.apply_platt(cal,raw)
    chosen=core.select_per_corridor_with_cooldown(te,prob,threshold,state)
    portfolio=core.select_portfolio_from_candidates(te,prob,chosen,portfolio_state)
    pred=te[['date','corridor','target','forward_bps','symmetric_bps','regret_bps','session_ordinal']].copy()
    pred['probability']=prob;pred['raw_probability']=raw;pred['candidate_signal']=pred.index.isin(chosen);pred['signal']=pred.index.isin(portfolio)
    pred['config_id']=spec['name'];pred['fold_test_year']=cutoff.year;pred['cutoff']=str(cutoff.date())
    name=spec['name']+'_'+str(cutoff.date());out=OUT/'output';out.mkdir(exist_ok=True)
    predpath=out/f'{name}_predictions.csv.gz';pred.to_csv(predpath,index=False)
    ckpt=out/f'{name}_head.joblib';joblib.dump({'model':model,'calibrator':cal,'threshold':threshold,'features':features,'spec':spec},ckpt)
    valid=te.available_at.notna()
    assert (te.loc[valid,'available_at']<=te.loc[valid,'decision_at']).all()
    receipt={'spec':spec,'cutoff':cutoff,'train_start':tr.date.min(),'train_end':tr.date.max(),'train_rows':len(tr),'train_latest_label':future.loc[tr.index].max(),'validation_start':va.date.min(),'validation_end':va.date.max(),'validation_latest_label':future.loc[va.index].max(),'validation_rows':len(va),'test_start':te.date.min(),'test_end':te.date.max(),'test_rows':len(te),'history_start':history.date.min(),'history_end':history.date.max(),'initial_candidate_state':state,'features':features,'head_parameters':model.named_steps['classifier'].get_params(),'train_oxr_coverage':float(tr.oxr_available.mean()),'validation_oxr_coverage':float(va.oxr_available.mean()),'test_oxr_coverage':float(te.oxr_available.mean()),'test_oxr_age_min_days':float(te.oxr_age_days.min()),'test_oxr_age_max_days':float(te.oxr_age_days.max()),'forecast_cache':str(cache.relative_to(ROOT)),'forecast_cache_sha256':sha(cache),'head_sha256':sha(ckpt),'predictions_sha256':sha(predpath),'source_sha256':sha(SNAPSHOT),'features_frame_sha256':hashlib.sha256(pd.util.hash_pandas_object(p[['date','corridor',*features]],index=False).to_numpy().tobytes()).hexdigest(),'code_sha256':sha(__file__),'protocol_sha256':sha(OUT/'protocol.json'),'elapsed_seconds':time.perf_counter()-t,'checks':{'train_labels_before_calibration':True,'calibration_labels_before_test':True,'forecast_features_present_on_all_used_rows':True,'oxr_availability_before_decision':True}}
    save(out/f'{name}_receipt.json',receipt)
    print(name,len(tr),len(te),round(receipt['elapsed_seconds'],2),flush=True)
    return pred


def summarize(data):
    rows=[]
    for (cid,cutoff),f in data.groupby(['config_id','cutoff']):
        for scope in ['all','KZT']:
            if scope=='all' and len(f.corridor.unique())==1:continue
            g=f if scope=='all' else f[f.corridor.eq('KZT')]
            rows.append({'config_id':cid,'cutoff':cutoff,'scope':scope,**score(g)})
    return pd.DataFrame(rows)


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--phase',choices=['protocol','development','test'],required=True);args=parser.parse_args()
    freeze_protocol()
    if args.phase=='protocol':return
    assert SNAPSHOT.exists(),'Root source snapshot is not yet ready'
    if args.phase=='test':assert (OUT/'selection.json').exists(),'Freeze development selection before computing2026 predictions'
    builder=FeatureBuilder();results=[]
    cutoffs=['2023-01-01','2024-01-01','2025-01-01'] if args.phase=='development' else ['2026-01-01','2026-03-01']
    with threadpool_limits(limits=1):
        for spec in specs():
            for cutoff in cutoffs:
                year=pd.Timestamp(cutoff).year
                p,features,cache=builder.build(spec,year)
                results.append(evaluate(p,features,cache,spec,cutoff))
    data=pd.concat(results,ignore_index=True);data.to_csv(OUT/f'{args.phase}_predictions.csv.gz',index=False)
    summarize(data).to_csv(OUT/f'{args.phase}_metrics.csv',index=False)
    if args.phase=='development':
        choices={}
        for scope,candidates in {'all':['synth_no_oxr','synth_basis2010_D2','synth_full2010_D2'],'KZT':['synth_kzt_no_oxr','synth_kzt_halyk_D2','synth_kzt_basis2010_D2','synth_kzt_basis2010_halyk_D2']}.items():
            scores={cid:float(np.mean((data.loc[data.config_id.eq(cid),'probability']-data.loc[data.config_id.eq(cid),'target'])**2)) for cid in candidates}
            choices[scope]={'selected':min(scores,key=scores.get),'brier':scores}
        save(OUT/'selection.json',{'frozen_at_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'selection_unix':time.time(),'choices':choices,'criterion':'predeclared development Brier only; no2026predictions computed yet','development_predictions_sha256':sha(OUT/'development_predictions.csv.gz'),'protocol_sha256':sha(OUT/'protocol.json')})
        print(json.dumps(choices,indent=2))


if __name__=='__main__':main()
